import type { AppDef, Field, ModuleMeta } from "./catalog";

const conn = (app: string, label = "Connection"): Field => ({ key: "connectionId", label, type: "connection", app, required: true });
const t = (key: string, label: string, extra: Partial<Field> = {}): Field => ({ key, label, type: "text", ...extra });
const ta = (key: string, label: string, extra: Partial<Field> = {}): Field => ({ key, label, type: "textarea", ...extra });
const num = (key: string, label: string, extra: Partial<Field> = {}): Field => ({ key, label, type: "number", ...extra });
const sel = (key: string, label: string, opts: [string, string][], def?: string, extra: Partial<Field> = {}): Field => ({
  key,
  label,
  type: "select",
  options: opts.map(([value, label]) => ({ value, label })),
  default: def ?? opts[0][0],
  ...extra,
});
const every: Field = { key: "intervalMin", label: "Check every (minutes)", type: "number", default: 15, help: "Your plan sets the fastest allowed interval." };

/** shorthand for an action module */
const act = (m: Omit<ModuleMeta, "credits"> & { credits?: number }): ModuleMeta => ({ credits: 1, ...m });
/** shorthand for a watch trigger */
const watch = (m: Omit<ModuleMeta, "credits" | "trigger" | "poll" | "category">): ModuleMeta => ({ ...m, category: "Triggers", trigger: true, poll: true, credits: 0, fields: [...m.fields, every] });

