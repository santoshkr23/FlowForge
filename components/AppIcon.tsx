export function AppIcon({ app, color, size = 18 }: { app: string; color?: string; size?: number }) {
  const Icon = ICONS[app];
  const box = size + 14;
  return (
    <span className="inline-flex shrink-0 items-center justify-center rounded-lg font-display font-bold text-white" style={{ background: color ?? "#2B59C3", width: box, height: box, fontSize: Math.round(size * 0.85) }} aria-hidden>
      {Icon ? <Icon size={size} strokeWidth={2} /> : (LETTERS[app] ?? app.charAt(0).toUpperCase())}
    </span>
  );
}
